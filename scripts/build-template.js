#!/usr/bin/env node
'use strict';
/**
 * build-template.js — template 的唯一建置入口
 *
 * source of truth：generator/template-src.html（可直接編輯的完整 HTML）
 * 產物：generator/generator-template.js（base64 的 window.TRIP_TMPL_B64，
 *       由 generator 與 /v/ 檢視器在瀏覽器端解碼使用）
 *
 * 用法：
 *   node scripts/build-template.js           # template-src.html → generator-template.js
 *   node scripts/build-template.js --check   # 只驗證兩邊一致（防 drift），不寫檔
 *
 * 修改 template 的新工作流：
 *   1. 直接編輯 generator/template-src.html
 *   2. node scripts/build-template.js
 *   3. 兩個檔案一起 commit
 *   （舊的一次性 patch-*.js 腳本已封存於 scripts/archive/，不再使用）
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC  = path.join(ROOT, 'generator', 'template-src.html');
const OUT  = path.join(ROOT, 'generator', 'generator-template.js');

const CHECK = process.argv.includes('--check');

// ─── 讀取 + 驗證 source ───────────────────────────────────────────────────────
const html = fs.readFileSync(SRC, 'utf8');

// 1. 佔位符齊全（buildIndexHtml / v/index.html 依賴這些 token）
const REQUIRED_TOKENS = [
  '__THEME_COLOR__', '__THEME_ACCENT__', '__THEME_LIGHT__',
  '__BG_COLOR__', '__BG_PALE__',
  '__TRIP_TITLE__', '__SHORT_TITLE__', '__TRIP_SUBTITLE__',
  '__DATE_PILL__', '__DURATION_PILL__', '__PEOPLE_PILL__',
  '__TRIP_PIN__', '__TRIP_CONFIG__',
];
const missing = REQUIRED_TOKENS.filter(t => !html.includes(t));
if (missing.length) throw new Error('template-src.html 缺少佔位符: ' + missing.join(', '));
console.log(`  ✓ ${REQUIRED_TOKENS.length} 個佔位符齊全`);

// 2. /v/ 檢視器的 SW 剝離依賴這個字串原樣存在
if (!html.includes('navigator.serviceWorker.register')) {
  throw new Error('template-src.html 缺少 navigator.serviceWorker.register（/v/ 的 SW 剝離會失效）');
}
console.log('  ✓ SW register 字串存在（/v/ 剝離點）');

// 3. inline script 語法檢查（token 換成合法值後 new Function）
const scriptMatch = html.match(/<script>([\s\S]*?)<\/script>\s*<\/body>/);
if (!scriptMatch) throw new Error('找不到 </body> 前的 inline script');
const synCode = scriptMatch[1]
  .replace(/__TRIP_CONFIG__/g, '{}')
  .replace(/"__TRIP_PIN__"/g, '"0000"');
try { new Function(synCode); } catch (e) { throw new Error('inline script 語法錯誤: ' + e.message); }
console.log('  ✓ inline script 語法檢查');

// 4. 行程排序函式在產生器與 App 模板必須逐字相同，產生器畫面才會等於輸出順序
const genSrc = fs.readFileSync(path.join(ROOT, 'generator', 'generator-app.js'), 'utf8');
const fnSrc = (src, name) => {
  const i = src.indexOf('function ' + name + '(');
  if (i < 0) return null;
  let d = 0;
  for (let k = src.indexOf('{', i); k < src.length; k++) {
    if (src[k] === '{') d++;
    else if (src[k] === '}' && --d === 0) return src.slice(i, k + 1);
  }
  return null;
};
for (const name of ['_insertByTime', '_minimalTimeOrder']) {
  const a = fnSrc(html, name), b = fnSrc(genSrc, name);
  if (!a || !b || a !== b) throw new Error(`${name} 在 template-src.html 與 generator-app.js 不一致`);
}
console.log('  ✓ 行程排序函式兩邊一致（_insertByTime、_minimalTimeOrder）');

// ─── encode + roundtrip ───────────────────────────────────────────────────────
const b64 = Buffer.from(html, 'utf8').toString('base64');
if (Buffer.from(b64, 'base64').toString('utf8') !== html) throw new Error('base64 roundtrip 失敗');
console.log('  ✓ base64 roundtrip');

const out = `// AUTO-GENERATED — do not edit this file directly.
// Source of truth: generator/template-src.html
// Rebuild: node scripts/build-template.js
window.TRIP_TMPL_B64 = '${b64}';
`;

// ─── --check：只比對，不寫檔 ─────────────────────────────────────────────────
if (CHECK) {
  const cur = fs.readFileSync(OUT, 'utf8');
  const curM = cur.match(/window\.TRIP_TMPL_B64 = '([A-Za-z0-9+/=]+)'/);
  if (!curM) throw new Error('generator-template.js 找不到 TRIP_TMPL_B64');
  if (curM[1] !== b64) {
    console.error('✗ DRIFT：template-src.html 與 generator-template.js 不一致。');
    console.error('  請執行 node scripts/build-template.js 重建後一起 commit。');
    process.exit(1);
  }
  console.log('\n✅ --check 通過：兩邊一致。');
  process.exit(0);
}

fs.writeFileSync(OUT, out, 'utf8');
console.log(`\n✅ 已寫入 generator/generator-template.js（${b64.length} chars base64）`);
